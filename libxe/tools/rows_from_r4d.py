"""rows_from_r4d.py -- copy libr4d's kernel rows for the adapters a port defines.

    rows_from_r4d.py libr4d/r4d_rows.cpp libxe/ports/<unit>.cpp OUT.inc [skip_adapter ...]

Every row of r4d_rows.cpp's kernel table whose launch is an adapter `r4d_rad_*` the port defines is
copied, with the constraint arrays it names. The trailing hooks after `launch` (scratch, layout,
relayout, opd_shape, unrelayout, replaces) are copied only where the port defines them; the others
become nullptr (libref describes operands for the tools). The output is included by xe_registry.cpp
and committed, like the port itself.
"""
import re
import sys

rows_src, port, out = sys.argv[1], sys.argv[2], sys.argv[3]
skip = set(sys.argv[4:])
rows = open(rows_src).read()
# Ops libref declares a schema for: a libxe row for any other op cannot load (libxe declares none).
ref_ops = set(re.findall(r'^\{ "([^"]+)", ARR\(',
                         open(rows_src.replace('libr4d/r4d_rows.cpp', 'libref/ref_registry.cpp')).read(), re.M))
ptxt = open(port).read()
DEF = r'extern "C" (?:int|long long|int64_t|void\*?|const \w+\*?)\s+(r4d_\w+)\s*\('
defined = set(re.findall(DEF, ptxt))
adapters = {a for a in defined if a.startswith('r4d_rad_')} - skip
# libr4d's host-side weight-layout hooks, which libxe compiles unchanged (libxe/CMakeLists.txt):
# a row keeps its layout / relayout / unrelayout hooks when they are defined there.
for extra in ('r4d_fp8_layout.cpp', 'r4d_layout.cpp'):
    defined |= set(re.findall(DEF, open(rows_src.replace('r4d_rows.cpp', extra)).read()))

# kernel-table entries: a '{' at line start followed by a string literal, up to the matching '},'
entries = []
for m in re.finditer(r'^\{ "', rows, re.M):
    i, depth = m.start(), 0
    for j in range(i, len(rows)):
        c = rows[j]
        if c == '{': depth += 1
        elif c == '}':
            depth -= 1
            if depth == 0:
                entries.append(rows[i:j + 1])
                break
picked, consts = [], []
for e in entries:
    ids = re.findall(r'\b(r4d_\w+)\b', e)
    launch = [x for x in ids if x in adapters]
    if not launch or any(x in skip for x in ids):
        continue
    op = re.search(r'"[^"]+",\s*"([^"]+)"', e).group(1)
    if op not in ref_ops:
        print('  skipped (no libref schema for op %s): %s' % (op, re.search(r'"([^"]+)"', e).group(1)))
        continue
    # no tuning in milestone 1: a tunable table becomes NOTUNE, so the adapters read the defaults
    e = re.sub(r'\bROW\(\s*t[A-Z]\w*\s*\)\s*,\s*\w+', 'NOTUNE', e)
    # null every r4d_ hook the port does not define
    def fix(mm):
        name = mm.group(1)
        return name if name in defined else 'nullptr'
    # identifiers in code only: a comment or string naming a libr4d file or symbol stays as written
    parts = re.split(r'(/\*.*?\*/|"(?:[^"\\]|\\.)*")', e, flags=re.S)
    body = ''.join(p if (p.startswith('/*') or p.startswith('"')) else re.sub(r'\b(r4d_\w+)\b', fix, p)
                   for p in parts)
    picked.append(body)
    consts += re.findall(r'ROW\((c\w+)\)', e)
seen, cdefs = set(), []
for c in consts:
    if c in seen: continue
    seen.add(c)
    mm = re.search(r'static const RadConstraint\s+' + c + r'\s*\[\]\s*=\s*\{.*?\};', rows, re.S)
    if mm: cdefs.append(mm.group(0))
    else: print('constraint array not found:', c)
with open(out, 'w') as f:
    f.write('/* Generated by libxe/tools/rows_from_r4d.py from libr4d/r4d_rows.cpp (9eaf10d) for %s;\n'
            ' * committed. Rows: %d. */\n' % (port.split('/')[-1], len(picked)))
    f.write('#ifdef XE_ROWS_CONSTRAINTS\n' + '\n'.join(cdefs) + '\n#else\n')
    f.write(',\n'.join(picked) + ',\n#endif\n')
print('%d rows, %d constraint arrays, adapters %d' % (len(picked), len(cdefs), len(adapters)))
for e in picked:
    print('  ', re.search(r'"([^"]+)", "([^"]+)"', e).groups())
