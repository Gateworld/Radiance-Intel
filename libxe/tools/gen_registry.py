"""gen_registry.py -- regenerate every ports/<unit>.rows.inc and the two aggregates xe_registry.cpp
includes: ports/all_rows.inc (each unit's constraints, then its rows) and ports/adapters.inc (one
declaration per adapter the rows launch).

    gen_registry.py [unit:skip_adapter,skip_adapter ...]

Units are every ports/*.cpp; `unit:...` names adapters of that unit to leave out (matrix-unit rows
that libxe rewrites instead, or fusions with no libref schema the tool does not catch).
"""
import glob
import os
import re
import subprocess
import sys

X = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))     # libxe/
S = os.path.dirname(X)                                             # src/
skips = {}
for a in sys.argv[1:]:
    u, _, s = a.partition(':')
    skips[u] = [x for x in s.split(',') if x]
units = sorted(os.path.basename(p)[:-4] for p in glob.glob(X + '/ports/*.cpp'))
adapters = set()
protos = {}       # symbol -> its prototype as the port defines it
seen_c = set()    # constraint arrays already emitted by an earlier unit
with open(X + '/ports/all_rows.inc', 'w') as f:
    f.write('/* Generated by libxe/tools/gen_registry.py; committed. Included twice by xe_registry.cpp. */\n')
    for u in units:
        inc = '%s/ports/%s.rows.inc' % (X, u)
        r = subprocess.run(['python3', X + '/tools/rows_from_r4d.py', S + '/libr4d/r4d_rows.cpp',
                            '%s/ports/%s.cpp' % (X, u), inc] + skips.get(u, []),
                           capture_output=True, text=True)
        print('== %s: %s' % (u, (r.stdout + r.stderr).strip()))
        txt = open(inc).read()
        # a constraint array another unit's rows already define is dropped here
        def dedupe(m):
            if m.group(1) in seen_c:
                return '/* %s: defined by an earlier unit */' % m.group(1)
            seen_c.add(m.group(1))
            return m.group(0)
        txt = re.sub(r'static const RadConstraint\s+(c\w+)\s*\[\]\s*=\s*\{.*?\};', dedupe, txt, flags=re.S)
        open(inc, 'w').write(txt)
        if re.search(r'^\{ "', txt, re.M):
            f.write('#include "ports/%s.rows.inc"\n' % u)
        used = set(re.findall(r'\b(r4d_\w+)\b', txt.split('#else', 1)[-1]))
        src = open('%s/ports/%s.cpp' % (X, u)).read() + open(S + '/libr4d/r4d_fp8_layout.cpp').read()
        for sym in used:
            m = re.search(r'extern "C"\s+([^;{()]*?\b' + sym + r'\s*\([^{;]*\))\s*\{', src)
            if m:
                protos[sym] = ' '.join(m.group(1).split())
        adapters |= used
with open(X + '/ports/adapters.inc', 'w') as f:
    f.write('/* Generated by libxe/tools/gen_registry.py; committed. The hooks the rows name, declared\n'
            ' * as their ports define them. */\n')
    for a in sorted(adapters):
        if a in protos:
            f.write('extern "C" %s;\n' % protos[a])
        else:
            print('no prototype found for', a)
print('%d units, %d adapters' % (len(units), len(adapters)))
